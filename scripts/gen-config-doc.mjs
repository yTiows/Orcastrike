#!/usr/bin/env node
// Generates CONFIGURATION.md from config/settings-schema.js and config/defaults.js.
//   node scripts/gen-config-doc.mjs          write CONFIGURATION.md
//   node scripts/gen-config-doc.mjs --check  exit 1 if CONFIGURATION.md is out of date
// tests/config-doc.test.js runs the check, so the doc can't drift from the code.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { DEFAULTS } from "../config/defaults.js";
import { getPath, SCHEMA, V1_DEFAULTS_CLASSIFICATION } from "../config/settings-schema.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const DOC_PATH = join(ROOT, "CONFIGURATION.md");

const ENV = [
  ["CSFLOAT_API_KEY", "secret", "daemon env / `wrangler secret put` (Worker)", "unset → CSFloat NOT_CONFIGURED", "Never in the repo, client JS, logs, responses or backups; redacted in logs."],
  ["ORCASTRIKE_PORT", "developer_default", "daemon env", "8790", "Daemon binds 127.0.0.1 only."],
  ["ORCASTRIKE_DATA_DIR", "developer_default", "daemon env", "`.orcastrike-data/` (git-ignored)", "SQLite database and logs."],
  ["ORCASTRIKE_ENGINE_INTERVAL_MS", "developer_default", "daemon env", "30000", "Opportunity engine cycle."],
  ["ORCASTRIKE_CONTRACT_REPORT", "developer_default", "daemon env", "`tests/fixtures/live/CONTRACT_REPORT.json`", "Parser verification source (D-38)."],
  ["ORCASTRIKE_SYNTHETIC", "test only", "daemon env", "unset", "`1` flags every stored row SYNTHETIC; required for the upstream override."],
  ["ORCASTRIKE_UPSTREAM_OVERRIDE", "test only", "daemon env", "unset", "Loopback host only, and only with ORCASTRIKE_SYNTHETIC=1; anything else refuses to start."],
  ["ORCASTRIKE_ROOT", "test only", "launcher env", "unset", "Points scripts/orca.mjs at a scratch checkout (tests/orca.test.js)."],
  ["ORCASTRIKE_SCAN_NO_GIT", "test only", "secret-scan env", "unset", "`1` scans the working tree as if there were no git checkout (ZIP download)."],
  ["ALLOWED_ORIGINS", "developer_default", "wrangler.toml [vars]", "Pages origin + localhost:8788", "Worker CORS allow-list."],
  ["NTFY_TOPIC", "not implemented", "—", "—", "Push notifications are BLOCKED (Phase 0 unverified); nothing reads this."],
];

const DANGEROUS_ERRORS = [
  "`mode.operating = AUTOMATION` without `automation.level = L3` → rejected.",
  "`automation.level = L2 | L3` → rejected: no verified execution API (DATA_SOURCE_MATRIX #19/#20).",
  "`umbra.active = true` without `umbra.bankroll_cents` → rejected.",
  "`umbra.active = true` without SIGNAL_EVIDENCE and without the typed phrase `unproven edge` → rejected by POST /api/v2/umbra.",
  "`risk.MAX_AGGREGATE_OPEN_EXPOSURE + risk.MIN_FREE_CASH_RESERVE > 1` → rejected (browser).",
  "Any non-`user_setting` key sent to POST /api/v2/settings → rejected (`cannot be changed at runtime`).",
];

const fmt = (v) => (v === null ? "null" : v === undefined ? "" : typeof v === "object" ? `\`${JSON.stringify(v)}\`` : `\`${String(v)}\``);
const cell = (v) => String(v ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

export function v1Leaves(obj = DEFAULTS, prefix = "") {
  const out = [];
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === "object" && !Array.isArray(v)) out.push(...v1Leaves(v, key));
    else out.push(key);
  }
  return out;
}

function schemaValidation(e) {
  if (e.options) return `one of ${e.options.join(", ")}`;
  if (typeof e.default === "boolean") return "true / false";
  const parts = [];
  if (e.min !== undefined) parts.push(`min ${e.min}`);
  if (e.max !== undefined) parts.push(`max ${e.max}`);
  if (/^(s|days|min|trades|pairs|sales)$/.test(e.unit ?? "")) parts.push("integer");
  if (e.unit === "USD cents") parts.push("integer cents");
  return parts.join(", ") || (e.class === "user_setting" ? "shape-checked (see settings-schema.js)" : "fixed");
}

export function renderConfigDoc() {
  const lines = [
    "# Configuration",
    "",
    "Generated by `node scripts/gen-config-doc.mjs` from `config/settings-schema.js` and `config/defaults.js`. Do not edit by hand: `npm test` fails if this file is out of date.",
    "",
    "Every value that can change a displayed economic result is listed with its class, default, bounds, validation, persistence and dangerous combinations.",
    "",
    "| Class | Meaning |",
    "|---|---|",
    "| invariant | Fixed by the spec or a P0 rule. Not changeable at runtime. |",
    "| developer_default | Changeable only by editing code (a reviewed change with a documented source). |",
    "| user_setting | Changeable at runtime within its bounds; validated on write; persisted. Invalid writes are rejected whole (fail closed). |",
    "",
    "## Research daemon settings",
    "",
    "Written through POST /api/v2/settings (same-origin, JSON). Only `user_setting` keys are accepted. Every change is appended to `settings_history`.",
    "",
    "| Key | Class | Default | Unit | Validation | Persistence | Meaning | Dangerous when |",
    "|---|---|---|---|---|---|---|---|",
    ...SCHEMA.map((e) => `| \`${e.key}\` | ${e.class} | ${cell(fmt(e.default))} | ${cell(e.unit ?? "")} | ${cell(schemaValidation(e))} | ${cell(e.persistence)} | ${cell(e.doc)} | ${cell(e.dangerous ?? "")} |`),
    "",
    "## Browser settings and v1 defaults",
    "",
    "`config/defaults.js` (deep-frozen). User overrides are validated in `js/state.js` / `js/tiers.js`; an invalid stored value is ignored and reported, never partially applied.",
    "",
    "| Key | Class | Default | Validation | Persistence | Dangerous when |",
    "|---|---|---|---|---|---|",
    ...v1Leaves().map((k) => {
      const [cls, persistence, validation, dangerous] = V1_DEFAULTS_CLASSIFICATION[k] ?? ["UNCLASSIFIED", "", "", ""];
      return `| \`${k}\` | ${cls} | ${cell(fmt(getPath(DEFAULTS, k)))} | ${cell(validation)} | ${cell(persistence)} | ${cell(dangerous ?? "")} |`;
    }),
    "",
    "## Environment variables",
    "",
    "| Name | Class | Where | Default | Notes |",
    "|---|---|---|---|---|",
    ...ENV.map((r) => `| \`${r[0]}\` | ${r.slice(1).map(cell).join(" | ")} |`),
    "",
    "## Dangerous combinations",
    "",
    "Rejected outright:",
    "",
    ...DANGEROUS_ERRORS.map((d) => `- ${d}`),
    "",
    "Accepted, with a warning. Daemon settings return it from POST /api/v2/settings and the Settings tab shows it on save; for browser settings the warning is documented here only:",
    "",
    ...SCHEMA.filter((e) => e.dangerous).map((e) => `- \`${e.key}\`: ${e.dangerous}`),
    ...Object.entries(V1_DEFAULTS_CLASSIFICATION)
      .filter(([, v]) => v[3])
      .map(([k, v]) => `- \`${k}\`: ${v[3]}`),
    "",
    "No setting, mode or theme enables execution. `automation.level` L2/L3 cannot be set while `EXECUTION_API_VERIFIED` is false in `js/research/automation.js`.",
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const doc = renderConfigDoc();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(DOC_PATH, "utf8").replace(/\r\n/g, "\n");
    } catch {
      /* missing */
    }
    if (current !== doc) {
      console.error("CONFIGURATION.md is out of date: run node scripts/gen-config-doc.mjs");
      process.exit(1);
    }
    console.log("CONFIGURATION.md up to date");
  } else {
    writeFileSync(DOC_PATH, doc);
    console.log(`wrote ${DOC_PATH}`);
  }
}
